// tp_allreduce_l0 — minimal Level Zero sample that demonstrates an
// AllReduce-sum across N discrete GPUs without staging through host memory.
//
// Algorithm (N ranks, main-rank gather/scatter):
//
//   * Single shared L0 context spans all participating devices.  Cross-device
//     copies and events created in this context can refer to USM allocated on
//     any of the devices.
//
//   * Rank 0 acts as "main" (coordinator).  Each worker rank w in [1..N-1]
//     copies its `local` buffer into a dedicated `main.incoming[w]` slot
//     residing in main's VRAM.  Main then runs N-1 accumulate kernels
//     (`result = local + incoming[0]; result += incoming[1]; ...`) on
//     all-local data and copies `result` back to every worker.
//
//   * Cross-device synchronization within a single submission uses L0 events
//     from a pool created with all devices.  No host-side step inside the
//     reduction loop.
//
//   * SOURCE-OWNED COPIES.  zeCommandListAppendMemoryCopy MUST be enqueued
//     on the command list of the device that OWNS the source memory.  If a
//     copy is enqueued on the destination device's list, the L0 driver
//     reports no error but the data is never transferred.  This is why the
//     gather step is enqueued on each worker, and the scatter step is
//     enqueued on main.
//
//   * Chunked pipelining.  The buffer is split into K chunks.  While main
//     reduces chunk i, workers can already be uploading chunk i+1 and main
//     can be scattering chunk i-1, overlapping kernel time with PCIe and
//     using PCIe in both directions concurrently.
//
//   * Dedicated copy engine.  When the device exposes a copy-only command
//     queue group (Link Copy Engine on dGPUs), gather/scatter copies run on
//     a dedicated copy queue so they overlap freely with kernel work on the
//     compute queue.  Falls back to the compute queue when no copy-only
//     group is available (typical for iGPUs).
//
// Scaling to N > 2:
//   Architecturally this sample is N-rank ready: vector<RankState>,
//   incoming[w] on main, ev_recv[c][w] / ev_bcast[c][w] events, kernel
//   accumulation chain.  However the main-rank gather/scatter algorithm has
//   PCIe cost ~ 2*(N-1)*bytes through main's link, which makes main the
//   bottleneck for N >= 3.  Production deployments with N >= 3 should switch
//   to ring-allreduce (asymptotically 2*bytes per link, INDEPENDENT of N) —
//   reachable on the same primitives (source-owned copies, cross-device
//   events) by arranging ranks in a ring and running reduce-scatter +
//   all-gather phases.  See the docstring on record_allreduce for the
//   integration plan.
//
// Usage:
//   ./tp_allreduce_l0 [num_elements] [iterations] [chunks]
//   ./tp_allreduce_l0 16777216 200 8         # 32 MB, 200 iters, 8 chunks

