// ---------------------------------------------------------------------------
// L0 error checking
// ---------------------------------------------------------------------------
#define ZE_CHECK(expr)                                                            \
    do {                                                                          \
        ze_result_t _r = (expr);                                                  \
        if (_r != ZE_RESULT_SUCCESS) {                                            \
            std::cerr << "L0 error 0x" << std::hex << static_cast<uint32_t>(_r)   \
                      << std::dec << " at " << __FILE__ << ":" << __LINE__        \
                      << " (" #expr ")" << std::endl;                             \
            std::exit(1);                                                         \
        }                                                                         \
    } while (0)

// Known f16 IEEE-754 bit patterns for fill / verification.
constexpr uint16_t kHalf1_0 = 0x3C00;  // 1.0h
constexpr uint16_t kHalf2_0 = 0x4000;  // 2.0h

// ---------------------------------------------------------------------------
// Per-rank state
// ---------------------------------------------------------------------------
struct RankState {
    ze_device_handle_t device = nullptr;
    std::string name;
    bool is_main = false;

    // Compute engine — runs the reduction kernel (main) and serves as a
    // copy-engine fallback for ranks that lack a copy-only group.
    uint32_t compute_ordinal = 0;
    ze_command_queue_handle_t compute_queue = nullptr;
    ze_command_list_handle_t compute_list = nullptr;

    // Copy engine — when a copy-only command queue group is exposed, gather
    // (worker) and scatter (main) copies run on a dedicated copy queue so
    // they overlap freely with compute and with each other (full-duplex PCIe).
    // When no copy-only group exists, `copy_*` aliases `compute_*`.
    uint32_t copy_ordinal = 0;
    bool has_dedicated_copy = false;
    ze_command_queue_handle_t copy_queue = nullptr;
    ze_command_list_handle_t copy_list = nullptr;

    // Reduction kernel (one per device, built from the embedded SPIR-V).
    ze_module_handle_t module = nullptr;
    ze_kernel_handle_t kernel = nullptr;

    // Device USM allocated on this device's VRAM.
    void* local = nullptr;                 // this rank's input contribution
    void* result = nullptr;                // AllReduce output
    std::vector<void*> incoming;           // main only: one per worker, [N-1]
};

// ---------------------------------------------------------------------------
// Driver / device enumeration
// ---------------------------------------------------------------------------
static bool pick_gpus(ze_driver_handle_t& driver,
                      std::vector<ze_device_handle_t>& devices,
                      int min_gpus, int max_gpus) {
    uint32_t dcount = 0;
    ZE_CHECK(zeDriverGet(&dcount, nullptr));
    std::vector<ze_driver_handle_t> drivers(dcount);
    ZE_CHECK(zeDriverGet(&dcount, drivers.data()));

    for (auto d : drivers) {
        uint32_t cnt = 0;
        zeDeviceGet(d, &cnt, nullptr);
        std::vector<ze_device_handle_t> all(cnt);
        zeDeviceGet(d, &cnt, all.data());

        std::vector<ze_device_handle_t> gpus;
        for (auto dh : all) {
            ze_device_properties_t prop{ZE_STRUCTURE_TYPE_DEVICE_PROPERTIES, nullptr};
            zeDeviceGetProperties(dh, &prop);
            if (prop.type == ZE_DEVICE_TYPE_GPU) {
                gpus.push_back(dh);
            }
        }
        if (static_cast<int>(gpus.size()) >= min_gpus) {
            int take = std::min<int>(max_gpus, static_cast<int>(gpus.size()));
            driver = d;
            devices.assign(gpus.begin(), gpus.begin() + take);
            return true;
        }
    }
    return false;
}

// ---------------------------------------------------------------------------
// Queue group selection
// ---------------------------------------------------------------------------
static void select_queue_groups(ze_device_handle_t dev,
                                uint32_t& compute_ordinal,
                                uint32_t& copy_ordinal,
                                bool& has_dedicated_copy) {
    uint32_t qg_count = 0;
    zeDeviceGetCommandQueueGroupProperties(dev, &qg_count, nullptr);
    std::vector<ze_command_queue_group_properties_t> qgp(
        qg_count, {ZE_STRUCTURE_TYPE_COMMAND_QUEUE_GROUP_PROPERTIES, nullptr});
    zeDeviceGetCommandQueueGroupProperties(dev, &qg_count, qgp.data());

    compute_ordinal = 0;
    copy_ordinal = 0;
    has_dedicated_copy = false;

    // First compute-capable group.
    for (uint32_t g = 0; g < qg_count; ++g) {
        if (qgp[g].flags & ZE_COMMAND_QUEUE_GROUP_PROPERTY_FLAG_COMPUTE) {
            compute_ordinal = g;
            break;
        }
    }
    // First copy-only group (preferred for P2P DMA on dGPUs).
    for (uint32_t g = 0; g < qg_count; ++g) {
        bool copy = (qgp[g].flags & ZE_COMMAND_QUEUE_GROUP_PROPERTY_FLAG_COPY);
        bool compute = (qgp[g].flags & ZE_COMMAND_QUEUE_GROUP_PROPERTY_FLAG_COMPUTE);
        if (copy && !compute) {
            copy_ordinal = g;
            has_dedicated_copy = true;
            break;
        }
    }
    if (!has_dedicated_copy) {
        copy_ordinal = compute_ordinal;
    }
}

// ---------------------------------------------------------------------------
// Per-rank init
// ---------------------------------------------------------------------------
static void init_rank(ze_context_handle_t ctx,
                      ze_device_handle_t dev,
                      RankState& rs,
                      size_t bytes) {
    rs.device = dev;

    ze_device_properties_t dp{ZE_STRUCTURE_TYPE_DEVICE_PROPERTIES, nullptr};
    zeDeviceGetProperties(dev, &dp);
    rs.name = dp.name;

    select_queue_groups(dev, rs.compute_ordinal, rs.copy_ordinal, rs.has_dedicated_copy);

    // Compute queue + list (ASYNC: Execute returns immediately).
    {
        ze_command_queue_desc_t qd{ZE_STRUCTURE_TYPE_COMMAND_QUEUE_DESC, nullptr};
        qd.ordinal = rs.compute_ordinal;
        qd.mode = ZE_COMMAND_QUEUE_MODE_ASYNCHRONOUS;
        qd.priority = ZE_COMMAND_QUEUE_PRIORITY_NORMAL;
        ZE_CHECK(zeCommandQueueCreate(ctx, dev, &qd, &rs.compute_queue));

        ze_command_list_desc_t ld{ZE_STRUCTURE_TYPE_COMMAND_LIST_DESC, nullptr};
        ld.commandQueueGroupOrdinal = rs.compute_ordinal;
        ZE_CHECK(zeCommandListCreate(ctx, dev, &ld, &rs.compute_list));
    }

    // Copy queue + list (dedicated if available, otherwise alias compute).
    if (rs.has_dedicated_copy) {
        ze_command_queue_desc_t qd{ZE_STRUCTURE_TYPE_COMMAND_QUEUE_DESC, nullptr};
        qd.ordinal = rs.copy_ordinal;
        qd.mode = ZE_COMMAND_QUEUE_MODE_ASYNCHRONOUS;
        qd.priority = ZE_COMMAND_QUEUE_PRIORITY_NORMAL;
        ZE_CHECK(zeCommandQueueCreate(ctx, dev, &qd, &rs.copy_queue));

        ze_command_list_desc_t ld{ZE_STRUCTURE_TYPE_COMMAND_LIST_DESC, nullptr};
        ld.commandQueueGroupOrdinal = rs.copy_ordinal;
        ZE_CHECK(zeCommandListCreate(ctx, dev, &ld, &rs.copy_list));
    } else {
        rs.copy_queue = rs.compute_queue;
        rs.copy_list  = rs.compute_list;
    }

    // Build kernel from embedded SPIR-V.
    ze_module_desc_t md{ZE_STRUCTURE_TYPE_MODULE_DESC, nullptr};
    md.format = ZE_MODULE_FORMAT_IL_SPIRV;
    md.inputSize = kAllReduceSumSpvSize;
    md.pInputModule = reinterpret_cast<const uint8_t*>(kAllReduceSumSpv);
    md.pBuildFlags = "-cl-std=CL2.0";
    ze_module_build_log_handle_t blog = nullptr;
    ze_result_t br = zeModuleCreate(ctx, dev, &md, &rs.module, &blog);
    if (br != ZE_RESULT_SUCCESS) {
        size_t lsz = 0;
        zeModuleBuildLogGetString(blog, &lsz, nullptr);
        std::vector<char> lbuf(lsz);
        zeModuleBuildLogGetString(blog, &lsz, lbuf.data());
        std::cerr << "[" << rs.name << "] module build failed: " << lbuf.data() << std::endl;
        std::exit(1);
    }
    if (blog) zeModuleBuildLogDestroy(blog);

    ze_kernel_desc_t kd{ZE_STRUCTURE_TYPE_KERNEL_DESC, nullptr};
    kd.pKernelName = "allreduce_sum_f16";
    ZE_CHECK(zeKernelCreate(rs.module, &kd, &rs.kernel));

    // Local input + output buffers on this device's VRAM.
    ze_device_mem_alloc_desc_t mad{ZE_STRUCTURE_TYPE_DEVICE_MEM_ALLOC_DESC, nullptr};
    ZE_CHECK(zeMemAllocDevice(ctx, &mad, bytes, 64, dev, &rs.local));
    ZE_CHECK(zeMemAllocDevice(ctx, &mad, bytes, 64, dev, &rs.result));
    // `incoming[w]` slots are allocated by the caller (only for main).
}

// ---------------------------------------------------------------------------
// Helpers for one-shot fills and host readback (NOT part of the timed path)
// ---------------------------------------------------------------------------
static void fill_device(RankState& rs, size_t n, uint16_t pattern) {
    ZE_CHECK(zeCommandListAppendMemoryFill(rs.compute_list, rs.local, &pattern,
                                           sizeof(pattern), n * sizeof(uint16_t),
                                           nullptr, 0, nullptr));
    ZE_CHECK(zeCommandListClose(rs.compute_list));
    ZE_CHECK(zeCommandQueueExecuteCommandLists(rs.compute_queue, 1, &rs.compute_list, nullptr));
    ZE_CHECK(zeCommandQueueSynchronize(rs.compute_queue, UINT64_MAX));
    ZE_CHECK(zeCommandListReset(rs.compute_list));
}

static std::vector<uint16_t> readback(ze_context_handle_t ctx, RankState& rs, size_t n) {
    std::vector<uint16_t> host(n);
    ze_host_mem_alloc_desc_t hd{ZE_STRUCTURE_TYPE_HOST_MEM_ALLOC_DESC, nullptr};
    void* stage = nullptr;
    ZE_CHECK(zeMemAllocHost(ctx, &hd, n * sizeof(uint16_t), 64, &stage));
    ZE_CHECK(zeCommandListAppendMemoryCopy(rs.compute_list, stage, rs.result,
                                           n * sizeof(uint16_t), nullptr, 0, nullptr));
    ZE_CHECK(zeCommandListClose(rs.compute_list));
    ZE_CHECK(zeCommandQueueExecuteCommandLists(rs.compute_queue, 1, &rs.compute_list, nullptr));
    ZE_CHECK(zeCommandQueueSynchronize(rs.compute_queue, UINT64_MAX));
    ZE_CHECK(zeCommandListReset(rs.compute_list));
    std::memcpy(host.data(), stage, n * sizeof(uint16_t));
    zeMemFree(ctx, stage);
    return host;
}

// ---------------------------------------------------------------------------
// AllReduce plan (events + chunk layout)
//
// Event matrix:
//   ev_recv  [chunk c][worker w]  — worker signals after gathering chunk c
//                                   (in worker's copy_list); main waits on
//                                   all ev_recv[c][*] before kernel for c.
//   ev_reduce[chunk c]            — main signals on the LAST kernel of chunk
//                                   c's accumulate chain; main's copy_list
//                                   waits on it before scattering chunk c.
//   ev_bcast [chunk c][worker w]  — main signals after scattering chunk c to
//                                   worker w (in main's copy_list); worker w
//                                   waits on it so its queue-sync blocks
//                                   until its `result` is fully written.
// ---------------------------------------------------------------------------
struct AllReducePlan {
    int num_ranks = 0;
    int num_workers = 0;     // num_ranks - 1
    int num_chunks = 1;
    std::vector<size_t> chunk_n;       // [num_chunks]
    std::vector<size_t> chunk_off;     // [num_chunks] in elements

    ze_event_pool_handle_t pool = nullptr;
    // Flattened as [c*num_workers + w].
    std::vector<ze_event_handle_t> ev_recv;
    std::vector<ze_event_handle_t> ev_bcast;
    // [c]
    std::vector<ze_event_handle_t> ev_reduce;

    ze_event_handle_t& recv(int c, int w)  { return ev_recv [c * num_workers + w]; }
    ze_event_handle_t& bcast(int c, int w) { return ev_bcast[c * num_workers + w]; }
};

static void build_plan(ze_context_handle_t ctx,
                       const std::vector<ze_device_handle_t>& devs,
                       int num_ranks, int num_chunks, size_t n,
                       AllReducePlan& plan) {
    plan.num_ranks = num_ranks;
    plan.num_workers = num_ranks - 1;
    plan.num_chunks = num_chunks;

    // Equal-ish chunk sizes; last chunk absorbs the remainder.
    size_t base = (n + num_chunks - 1) / num_chunks;
    plan.chunk_n.resize(num_chunks);
    plan.chunk_off.resize(num_chunks);
    size_t off = 0;
    for (int c = 0; c < num_chunks; ++c) {
        size_t this_n = std::min<size_t>(base, n - off);
        plan.chunk_n[c]   = this_n;
        plan.chunk_off[c] = off;
        off += this_n;
    }

    const uint32_t per_chunk = static_cast<uint32_t>(2 * plan.num_workers + 1);
    const uint32_t total_events = per_chunk * static_cast<uint32_t>(num_chunks);

    ze_event_pool_desc_t epd{ZE_STRUCTURE_TYPE_EVENT_POOL_DESC, nullptr};
    epd.flags = 0;
    epd.count = total_events;
    // zeEventPoolCreate wants non-const phDevices; copy the handles.
    std::vector<ze_device_handle_t> devs_nc(devs.begin(), devs.end());
    ZE_CHECK(zeEventPoolCreate(ctx, &epd,
                               static_cast<uint32_t>(devs_nc.size()),
                               devs_nc.data(), &plan.pool));

    plan.ev_recv  .resize(num_chunks * plan.num_workers);
    plan.ev_bcast .resize(num_chunks * plan.num_workers);
    plan.ev_reduce.resize(num_chunks);

    uint32_t idx = 0;
    auto create = [&](ze_event_handle_t& dst) {
        ze_event_desc_t ed{ZE_STRUCTURE_TYPE_EVENT_DESC, nullptr};
        ed.signal = ZE_EVENT_SCOPE_FLAG_DEVICE;
        ed.wait   = ZE_EVENT_SCOPE_FLAG_DEVICE;
        ed.index  = idx++;
        ZE_CHECK(zeEventCreate(plan.pool, &ed, &dst));
    };
    for (int c = 0; c < num_chunks; ++c) {
        for (int w = 0; w < plan.num_workers; ++w) create(plan.recv(c, w));
        create(plan.ev_reduce[c]);
        for (int w = 0; w < plan.num_workers; ++w) create(plan.bcast(c, w));
    }
}

static void destroy_plan(AllReducePlan& plan) {
    for (auto& e : plan.ev_recv)   if (e) zeEventDestroy(e);
    for (auto& e : plan.ev_bcast)  if (e) zeEventDestroy(e);
    for (auto& e : plan.ev_reduce) if (e) zeEventDestroy(e);
    if (plan.pool) zeEventPoolDestroy(plan.pool);
}

// Reset all events on host between iterations.  Cheap: no driver work.
static void host_reset_plan(AllReducePlan& plan) {
    for (auto& e : plan.ev_recv)   ZE_CHECK(zeEventHostReset(e));
    for (auto& e : plan.ev_bcast)  ZE_CHECK(zeEventHostReset(e));
    for (auto& e : plan.ev_reduce) ZE_CHECK(zeEventHostReset(e));
}

// ---------------------------------------------------------------------------
// Record AllReduce command lists (N-rank, chunked, optional copy engine)
//
// Worker w (w = 1..N-1) does, on its copy_list:
//   for c in 0..K-1: copy local[chunk c] -> main.incoming[w-1][chunk c]
//                    signal ev_recv[c][w-1]
//   for c in 0..K-1: wait ev_bcast[c][w-1]
//
// Main does:
//   On compute_list, for c in 0..K-1:
//     wait ev_recv[c][0..N-2]
//     kernel(result[c], local[c], incoming[0][c])          // first source
//     kernel(result[c], result[c], incoming[w][c]) for w=1..N-2  // accumulate
//     last kernel signals ev_reduce[c]
//   On copy_list, for c in 0..K-1:
//     for w in 0..N-2:
//       wait ev_reduce[c]
//       copy main.result[chunk c] -> ranks[w+1].result[chunk c]
//       signal ev_bcast[c][w]
//
// ---------------------------------------------------------------------------
// Plugin-integration notes:
//   * Replace `RankState.local / .result / .incoming[w]` with USM pointers
//     provided by the intel_gpu memory pool (cldnn::memory device buffer).
//   * Build the kernel module and resolve `allreduce_sum_<dtype>` variants
//     (f16, bf16, f32) once per TpAllReducePrimitive, indexed by element type.
//   * Pre-record one command-list pair per (shape, chunk-count, dtype) and
//     cache; per-inference call = host_reset_plan + Execute on all queues +
//     Synchronize.  No allocations in the hot path.
//   * For N >= 3, replace record_allreduce with a ring-based recorder
//     (reduce-scatter + all-gather over N-1 ring steps) using the same
//     primitives (source-owned MemoryCopy, ev_recv/ev_send pairs).
// ---------------------------------------------------------------------------
static void record_allreduce(std::vector<RankState>& ranks, AllReducePlan& plan) {
    constexpr uint32_t kGroupSize = 256;
    RankState& main_rs = ranks[0];
    const int K = plan.num_chunks;
    const int W = plan.num_workers;

    auto chunk_ptr = [](void* base, size_t elem_off) -> void* {
        return reinterpret_cast<uint8_t*>(base) + elem_off * sizeof(uint16_t);
    };

    // --- Worker command lists ------------------------------------------------
    for (int w = 0; w < W; ++w) {
        RankState& worker = ranks[w + 1];
        // K gather copies, each signals ev_recv[c][w].
        for (int c = 0; c < K; ++c) {
            size_t cn = plan.chunk_n[c];
            size_t co = plan.chunk_off[c];
            ZE_CHECK(zeCommandListAppendMemoryCopy(
                worker.copy_list,
                chunk_ptr(main_rs.incoming[w], co),
                chunk_ptr(worker.local, co),
                cn * sizeof(uint16_t),
                plan.recv(c, w),
                0, nullptr));
        }
        // Wait for all of OUR scatter chunks to land before queue-sync returns.
        for (int c = 0; c < K; ++c) {
            ZE_CHECK(zeCommandListAppendWaitOnEvents(worker.copy_list, 1,
                                                     &plan.bcast(c, w)));
        }
    }

    // --- Main compute list ---------------------------------------------------
    // Per chunk: wait all ev_recv[c][*], run (N-1) accumulate kernels,
    // last one signals ev_reduce[c].
    ZE_CHECK(zeKernelSetGroupSize(main_rs.kernel, kGroupSize, 1, 1));
    for (int c = 0; c < K; ++c) {
        // Wait for all workers' chunk c to arrive in main.incoming.
        std::vector<ze_event_handle_t> waits(W);
        for (int w = 0; w < W; ++w) waits[w] = plan.recv(c, w);
        if (W > 0) {
            ZE_CHECK(zeCommandListAppendWaitOnEvents(main_rs.compute_list,
                                                     static_cast<uint32_t>(W),
                                                     waits.data()));
        }

        size_t cn = plan.chunk_n[c];
        size_t co = plan.chunk_off[c];
        uint64_t cn64 = cn;
        uint32_t items = static_cast<uint32_t>(cn);
        ze_group_count_t gc{(items + kGroupSize - 1) / kGroupSize, 1, 1};

        void* result_c   = chunk_ptr(main_rs.result, co);
        void* local_c    = chunk_ptr(main_rs.local, co);

        // Accumulate N-1 worker contributions.  At least 1 worker exists
        // (asserted in main()), so the loop runs at least once.
        for (int w = 0; w < W; ++w) {
            void* src0 = (w == 0) ? local_c : result_c;
            void* incoming_c = chunk_ptr(main_rs.incoming[w], co);
            ZE_CHECK(zeKernelSetArgumentValue(main_rs.kernel, 0, sizeof(void*), &result_c));
            ZE_CHECK(zeKernelSetArgumentValue(main_rs.kernel, 1, sizeof(void*), &src0));
            ZE_CHECK(zeKernelSetArgumentValue(main_rs.kernel, 2, sizeof(void*), &incoming_c));
            ZE_CHECK(zeKernelSetArgumentValue(main_rs.kernel, 3, sizeof(cn64), &cn64));
            ze_event_handle_t signal = (w == W - 1) ? plan.ev_reduce[c] : nullptr;
            ZE_CHECK(zeCommandListAppendLaunchKernel(main_rs.compute_list,
                                                     main_rs.kernel, &gc,
                                                     signal, 0, nullptr));
        }
    }

    // --- Main copy list (scatter) -------------------------------------------
    // If copy list aliases compute list (no dedicated copy engine), the
    // appends below land on the same in-order list as the kernels above and
    // are naturally ordered after them.  We still emit explicit ev_reduce
    // waits so the dedicated-copy path works on dGPUs.
    for (int c = 0; c < K; ++c) {
        size_t cn = plan.chunk_n[c];
        size_t co = plan.chunk_off[c];
        for (int w = 0; w < W; ++w) {
            RankState& worker = ranks[w + 1];
            ZE_CHECK(zeCommandListAppendWaitOnEvents(main_rs.copy_list, 1,
                                                     &plan.ev_reduce[c]));
            ZE_CHECK(zeCommandListAppendMemoryCopy(
                main_rs.copy_list,
                chunk_ptr(worker.result, co),
                chunk_ptr(main_rs.result, co),
                cn * sizeof(uint16_t),
                plan.bcast(c, w),
                0, nullptr));
        }
    }
}

// Close all command lists that will be submitted.
static void close_lists(std::vector<RankState>& ranks) {
    for (auto& rs : ranks) {
        ZE_CHECK(zeCommandListClose(rs.compute_list));
        if (rs.has_dedicated_copy) {
            ZE_CHECK(zeCommandListClose(rs.copy_list));
        }
    }
}

static void reset_lists(std::vector<RankState>& ranks) {
    for (auto& rs : ranks) {
        ZE_CHECK(zeCommandListReset(rs.compute_list));
        if (rs.has_dedicated_copy) {
            ZE_CHECK(zeCommandListReset(rs.copy_list));
        }
    }
}

// Submit all queues and wait.  The order of submission matters only for
// kicking off work in parallel; cross-queue ordering is enforced by events.
static void submit_and_sync(std::vector<RankState>& ranks) {
    // Submit workers' copy lists first so their gather copies are visible to
    // main as early as possible.  Then main's lists.
    for (size_t i = 1; i < ranks.size(); ++i) {
        ZE_CHECK(zeCommandQueueExecuteCommandLists(ranks[i].copy_queue, 1,
                                                   &ranks[i].copy_list, nullptr));
        if (ranks[i].has_dedicated_copy) {
            // compute queue has no work for workers in this design.
        }
    }
    // Main: compute list (kernels) and copy list (scatter).
    ZE_CHECK(zeCommandQueueExecuteCommandLists(ranks[0].compute_queue, 1,
                                               &ranks[0].compute_list, nullptr));
    if (ranks[0].has_dedicated_copy) {
        ZE_CHECK(zeCommandQueueExecuteCommandLists(ranks[0].copy_queue, 1,
                                                   &ranks[0].copy_list, nullptr));
    }

    // Sync everything.
    for (auto& rs : ranks) {
        ZE_CHECK(zeCommandQueueSynchronize(rs.compute_queue, UINT64_MAX));
        if (rs.has_dedicated_copy) {
            ZE_CHECK(zeCommandQueueSynchronize(rs.copy_queue, UINT64_MAX));
        }
    }
}

// ---------------------------------------------------------------------------
// Tear-down
// ---------------------------------------------------------------------------
static void destroy_rank(ze_context_handle_t ctx, RankState& rs) {
    if (rs.local)   zeMemFree(ctx, rs.local);
    if (rs.result)  zeMemFree(ctx, rs.result);
    for (auto* p : rs.incoming) if (p) zeMemFree(ctx, p);
    if (rs.kernel)  zeKernelDestroy(rs.kernel);
    if (rs.module)  zeModuleDestroy(rs.module);
    if (rs.compute_list)  zeCommandListDestroy(rs.compute_list);
    if (rs.compute_queue) zeCommandQueueDestroy(rs.compute_queue);
    if (rs.has_dedicated_copy) {
        if (rs.copy_list)  zeCommandListDestroy(rs.copy_list);
        if (rs.copy_queue) zeCommandQueueDestroy(rs.copy_queue);
    }
}

// ---------------------------------------------------------------------------
// Main
// ---------------------------------------------------------------------------
int main(int argc, char* argv[]) {
    size_t n        = (argc > 1) ? static_cast<size_t>(std::stoull(argv[1]))
                                 : (16ULL * 1024 * 1024);  // 16M f16 = 32 MB
    int iterations  = (argc > 2) ? std::stoi(argv[2]) : 100;
    int num_chunks  = (argc > 3) ? std::stoi(argv[3]) : 8;
    constexpr int kMaxRanksDefault = 2;  // sample is validated on 2 dGPUs
    int max_ranks   = (argc > 4) ? std::stoi(argv[4]) : kMaxRanksDefault;
    if (num_chunks < 1) num_chunks = 1;

    std::cout << "tp_allreduce_l0\n"
              << "  elements:   " << n << " (f16, " << (n * 2) << " bytes)\n"
              << "  iterations: " << iterations << "\n"
              << "  chunks:     " << num_chunks << "\n" << std::endl;

    ZE_CHECK(zeInit(0));

    ze_driver_handle_t driver = nullptr;
    std::vector<ze_device_handle_t> devs;
    if (!pick_gpus(driver, devs, /*min*/ 2, /*max*/ max_ranks)) {
        std::cerr << "Need at least 2 GPUs under a single L0 driver." << std::endl;
        return 1;
    }
    const int N = static_cast<int>(devs.size());

    // === Single shared context covering all selected devices ===
    ze_context_desc_t ctx_desc{ZE_STRUCTURE_TYPE_CONTEXT_DESC, nullptr};
    ze_context_handle_t ctx = nullptr;
    ZE_CHECK(zeContextCreateEx(driver, &ctx_desc,
                               static_cast<uint32_t>(devs.size()),
                               devs.data(), &ctx));

    // === Per-rank setup ===
    std::vector<RankState> ranks(N);
    const size_t bytes = n * sizeof(uint16_t);
    constexpr int kMain = 0;
    for (int i = 0; i < N; ++i) {
        ranks[i].is_main = (i == kMain);
        init_rank(ctx, devs[i], ranks[i], bytes);
        std::cout << "  rank " << i << ": " << ranks[i].name
                  << (ranks[i].is_main ? "  [main]" : "  [worker]")
                  << "  (copy engine: "
                  << (ranks[i].has_dedicated_copy ? "dedicated" : "shared-with-compute")
                  << ")\n";
    }
    std::cout << std::endl;

    // Main allocates one `incoming[w]` slot per worker.
    ranks[kMain].incoming.assign(N - 1, nullptr);
    {
        ze_device_mem_alloc_desc_t mad{ZE_STRUCTURE_TYPE_DEVICE_MEM_ALLOC_DESC, nullptr};
        for (int w = 0; w < N - 1; ++w) {
            ZE_CHECK(zeMemAllocDevice(ctx, &mad, bytes, 64, ranks[kMain].device,
                                      &ranks[kMain].incoming[w]));
        }
    }

    // === Plan: events + chunk layout ===
    AllReducePlan plan;
    build_plan(ctx, devs, N, num_chunks, n, plan);

    // === P2P access matrix (sanity) ===
    std::cout << "  P2P access matrix (row -> col):\n";
    bool all_p2p = true;
    for (int i = 0; i < N; ++i) {
        std::cout << "    " << i << ":";
        for (int j = 0; j < N; ++j) {
            if (i == j) { std::cout << "  -"; continue; }
            ze_bool_t can = false;
            zeDeviceCanAccessPeer(devs[i], devs[j], &can);
            std::cout << "  " << (can ? "Y" : "N");
            if (!can) all_p2p = false;
        }
        std::cout << "\n";
    }
    if (!all_p2p) {
        std::cerr << "  WARNING: not all pairs have P2P; driver will fall back\n"
                  << "  to host-staged copies — performance will be reduced.\n";
    }
    std::cout << std::endl;

    // === Initial fill ===
    // rank 0 = 1.0h, rank 1 = 2.0h, rank 2 = 3.0h, ...  Expected sum =
    // 1 + 2 + ... + N (in halfs), bit pattern computed below.
    auto half_of = [](int v) -> uint16_t {
        // small integers 1..16 -> exact half representation.
        // We only use 1..2 here; for N>2 extension just generate via union.
        return (v == 1) ? kHalf1_0
             : (v == 2) ? kHalf2_0
             : 0;  // unused on this run, expected pattern is computed via host
    };
    for (int i = 0; i < N; ++i) {
        uint16_t pat = half_of(i + 1);
        // Fallback for i+1 > 2: encode via a tiny CPU-side IEEE-754-half.
        if (pat == 0) {
            float f = static_cast<float>(i + 1);
            uint32_t u; std::memcpy(&u, &f, 4);
            uint32_t sign = (u >> 31) & 0x1;
            int32_t  exp  = ((u >> 23) & 0xFF) - 127;
            uint32_t mant = u & 0x7FFFFF;
            uint16_t h_exp = static_cast<uint16_t>(exp + 15);
            uint16_t h_mant = static_cast<uint16_t>(mant >> 13);
            pat = static_cast<uint16_t>((sign << 15) | (h_exp << 10) | h_mant);
        }
        fill_device(ranks[i], n, pat);
    }
    // Expected = sum(1..N) as half.
    uint16_t expected_pat;
    {
        float s = 0.f;
        for (int i = 1; i <= N; ++i) s += static_cast<float>(i);
        uint32_t u; std::memcpy(&u, &s, 4);
        uint32_t sign = (u >> 31) & 0x1;
        int32_t  exp  = ((u >> 23) & 0xFF) - 127;
        uint32_t mant = u & 0x7FFFFF;
        uint16_t h_exp = static_cast<uint16_t>(exp + 15);
        uint16_t h_mant = static_cast<uint16_t>(mant >> 13);
        expected_pat = static_cast<uint16_t>((sign << 15) | (h_exp << 10) | h_mant);
    }

    // -----------------------------------------------------------------------
    // Correctness check: one AllReduce.
    // -----------------------------------------------------------------------
    record_allreduce(ranks, plan);
    close_lists(ranks);
    submit_and_sync(ranks);
    reset_lists(ranks);

    int total_failures = 0;
    for (int i = 0; i < N; ++i) {
        auto out = readback(ctx, ranks[i], n);
        size_t mismatches = 0;
        for (size_t k = 0; k < n; ++k)
            if (out[k] != expected_pat) ++mismatches;
        std::cout << "  rank " << i << " correctness: "
                  << (mismatches == 0 ? "PASS" : "FAIL")
                  << "  (" << mismatches << "/" << n << " mismatches)";
        std::cout << "\n    result[0..3] = 0x" << std::hex
                  << out[0] << " 0x" << out[1] << " 0x" << out[2] << " 0x" << out[3]
                  << "  (expected 0x" << expected_pat << ")" << std::dec;
        std::cout << std::endl;
        total_failures += static_cast<int>(mismatches);
    }

    if (total_failures != 0) {
        std::cerr << "\nAccuracy check failed; aborting before perf run." << std::endl;
        destroy_plan(plan);
        for (auto& rs : ranks) destroy_rank(ctx, rs);
        zeContextDestroy(ctx);
        return 2;
    }

    // -----------------------------------------------------------------------
    // Performance loop.  Command lists are recorded once and re-submitted.
    // -----------------------------------------------------------------------
    record_allreduce(ranks, plan);
    close_lists(ranks);

    constexpr int kWarmup = 5;
    for (int it = 0; it < kWarmup; ++it) {
        host_reset_plan(plan);
        submit_and_sync(ranks);
    }

    auto t0 = std::chrono::steady_clock::now();
    for (int it = 0; it < iterations; ++it) {
        host_reset_plan(plan);
        submit_and_sync(ranks);
    }
    auto t1 = std::chrono::steady_clock::now();
    double total_ms = std::chrono::duration<double, std::milli>(t1 - t0).count();
    double per_iter_us = (total_ms * 1000.0) / iterations;

    // PCIe traffic per iteration through main's link: (N-1) gathers in +
    // (N-1) scatters out = 2*(N-1)*bytes.  This is the bottleneck of the
    // gather/scatter algorithm; switch to ring-allreduce for N >= 3 to
    // achieve ~2*bytes per link (independent of N).
    double pcie_bytes = 2.0 * static_cast<double>(N - 1) * static_cast<double>(bytes);
    double pcie_bw_gbs = (pcie_bytes / 1.0e9) / (per_iter_us / 1.0e6);

    std::cout << "\n=== Performance ===\n"
              << std::fixed << std::setprecision(2)
              << "  iterations:        " << iterations << "\n"
              << "  total time:        " << total_ms << " ms\n"
              << "  per-iter latency:  " << per_iter_us << " us\n"
              << "  PCIe traffic/iter: " << pcie_bytes / 1.0e6
              << " MB (2*(N-1)*bytes through main)\n"
              << "  effective PCIe BW: " << pcie_bw_gbs << " GB/s"
              << std::endl;

    // -----------------------------------------------------------------------
    // Cleanup
    // -----------------------------------------------------------------------
    destroy_plan(plan);
    reset_lists(ranks);
    for (auto& rs : ranks) destroy_rank(ctx, rs);
    zeContextDestroy(ctx);

    std::cout << "\n  RESULT: " << (total_failures == 0 ? "PASS" : "FAIL")
              << std::endl;
    return total_failures == 0 ? 0 : 2;
}
